export type AbmTextKey = keyof typeof en

function isChineseLocale(locale: Locale): boolean {
  return locale === 'zh' || locale === 'zh-TW'
}

function format(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key) => String(params[key] ?? match))
}

export function useAbmText() {
  const locale = useSettingsStore((state) => state.locale)
  const dictionary = isChineseLocale(locale) ? zh : en
  return useMemo(
    () => (key: AbmTextKey, params?: Record<string, string | number>) => format(dictionary[key] ?? en[key], params),
    [dictionary],
  )
}

export function getAbmText(key: AbmTextKey, params?: Record<string, string | number>): string {
  const locale = useSettingsStore.getState().locale
  const dictionary = isChineseLocale(locale) ? zh : en
  return format(dictionary[key] ?? en[key], params)
}
